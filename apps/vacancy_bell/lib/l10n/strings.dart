final _placeholder = RegExp(r'\{(\w+)\}');

/// The `{names}` used in a template.
Set<String> placeholdersOf(String template) =>
    {for (final m in _placeholder.allMatches(template)) m.group(1)!};

/// Fills `{name}` placeholders from [args]; unknown names are left as is.
String fillTemplate(String template, Map<String, Object?> args) =>
    template.replaceAllMapped(_placeholder, (m) {
      final v = args[m.group(1)];
      return v == null ? m.group(0)! : '$v';
    });

/// Strings for one language.
class S {
  const S(this.lang);
  final Lang lang;

  static const en = S(Lang.en);
  static const hi = S(Lang.hi);

  static final _placeholder = RegExp(r'\{(\w+)\}');

  String t(T key) {
    final pair = kStrings[key];
    if (pair == null) return key.name;
    return lang == Lang.hi ? pair.$2 : pair.$1;
  }

  /// [t] with `{name}` placeholders filled from [args].
  String f(T key, Map<String, Object> args) => t(key).replaceAllMapped(
      _placeholder, (m) => args[m[1]]?.toString() ?? m[0]!);

  /// Placeholder names used in [text].
  static Set<String> placeholders(String text) =>
      {for (final m in _placeholder.allMatches(text)) m[1]!};

  String subject(String id) => switch (id) {
        'gk' => t(T.subjGk),
        'history' => t(T.subjHistory),
        'polity' => t(T.subjPolity),
        'geography' => t(T.subjGeography),
        'economy' => t(T.subjEconomy),
        'science' => t(T.subjScience),
        'current_affairs' => t(T.subjCurrentAffairs),
        'maths' => t(T.subjMaths),
        'reasoning' => t(T.subjReasoning),
        'english' => t(T.subjEnglish),
        'computer' => t(T.subjComputer),
        _ => id,
      };

  String exam(String id) => switch (id) {
        'ssc' => t(T.examSsc),
        'railway' => t(T.examRailway),
        'banking' => t(T.examBanking),
        'upsc' => t(T.examUpsc),
        'state_psc' => t(T.examStatePsc),
        'defence' => t(T.examDefence),
        'teaching' => t(T.examTeaching),
        _ => id,
      };

  String difficulty(Difficulty? d) => switch (d) {
        null => t(T.anyDifficulty),
        Difficulty.easy => t(T.easy),
        Difficulty.medium => t(T.medium),
        Difficulty.hard => t(T.hard),
      };

  String negative(NegativeMarking n) =>
      n == NegativeMarking.none ? t(T.noNegative) : n.label;

  (String, String) badge(Badge b) => switch (b) {
        Badge.firstQuiz => (t(T.badgeFirstQuiz), t(T.badgeFirstQuizDesc)),
        Badge.streak3 => (t(T.badgeStreak3), t(T.badgeStreak3Desc)),
        Badge.streak7 => (t(T.badgeStreak7), t(T.badgeStreak7Desc)),
        Badge.streak30 => (t(T.badgeStreak30), t(T.badgeStreak30Desc)),
        Badge.perfectDaily => (t(T.badgePerfectDaily), t(T.badgePerfectDailyDesc)),
        Badge.answered100 => (t(T.badgeAnswered100), t(T.badgeAnswered100Desc)),
        Badge.answered500 => (t(T.badgeAnswered500), t(T.badgeAnswered500Desc)),
        Badge.answered1000 => (t(T.badgeAnswered1000), t(T.badgeAnswered1000Desc)),
        Badge.firstMock => (t(T.badgeFirstMock), t(T.badgeFirstMockDesc)),
        Badge.allRounder => (t(T.badgeAllRounder), t(T.badgeAllRounderDesc)),
        Badge.caReader => (t(T.badgeCaReader), t(T.badgeCaReaderDesc)),
        Badge.sharpShooter => (t(T.badgeSharpShooter), t(T.badgeSharpShooterDesc)),
        Badge.level5 => (t(T.badgeLevel5), t(T.badgeLevel5Desc)),
        Badge.level10 => (t(T.badgeLevel10), t(T.badgeLevel10Desc)),
      };

  /// "just now", "5 min ago", "3 h ago", "2 days ago".
  String ago(DateTime then, DateTime now) {
    final d = now.difference(then);
    if (d.inMinutes < 1) return t(T.justNow);
    if (d.inHours < 1) return f(T.minutesAgo, {'n': d.inMinutes});
    if (d.inDays < 1) return f(T.hoursAgo, {'n': d.inHours});
    return f(T.daysAgo, {'n': d.inDays});
  }

  static const _monthsEn = [
    'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'
  ];
  static const _monthsHi = [
    'जन', 'फ़र', 'मार्च', 'अप्रैल', 'मई', 'जून',
    'जुलाई', 'अग', 'सित', 'अक्टू', 'नव', 'दिस'
  ];

  /// "7 Oct 2026" / "7 अक्टू 2026".
  String date(int year, int month, int day, {bool withYear = true}) {
    final m = (lang == Lang.hi ? _monthsHi : _monthsEn)[month - 1];
    return withYear ? '$day $m $year' : '$day $m';
  }
}
